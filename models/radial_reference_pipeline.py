#  WHAT THIS DOES (and why it differs from the old script)
#   1. ONE feature vector per recording.  Your simulated currents are exactly
#      periodic (all energy sits on multiples of the supply frequency), so the
#      27 cycles of a file are copies of one cycle.  Cutting a file into windows
#      only manufactures copies; it never adds information.
#   2. Proper signal processing: irregular Ansys time axis -> fine linear grid ->
#      anti-aliased decimation -> Park vector -> Fourier coefficients computed
