def _S(m):
    return make_pipeline(StandardScaler(), m)


class LevelCVRidge(BaseEstimator, RegressorMixin):
    """Ridge / linear-SVR regression whose regularisation is chosen by leave-one-LEVEL-out on its own
    training data (groups = target level, so SE_x and DE_x leave together).  Healthy (0%) is the anchor."""

    def __init__(self, kind="ridge", grid=(1e-3, 1e-2, 1e-1, 1.0, 10.0)):
        self.kind, self.grid = kind, grid

    def _mk(self, a):
        return _S(Ridge(a)) if self.kind == "ridge" else _S(SVR(kernel="linear", C=a, epsilon=1.0))

    def fit(self, X, y):
        X, y = np.asarray(X, float), np.asarray(y, float)
        best = (np.inf, self.grid[len(self.grid) // 2])
        levels = np.unique(y[y > 0])
        if len(levels) >= 3:
            for a in self.grid:
                err = []
                for L in levels:
                    te = y == L
                    p = np.clip(self._mk(a).fit(X[~te], y[~te]).predict(X[te]), 0, 100)
                    err += list(np.abs(p - y[te]))
                if np.mean(err) < best[0]:
                    best = (np.mean(err), a)
        self.alpha_ = best[1]
        self.model_ = self._mk(self.alpha_).fit(X, y)
        return self

    def predict(self, X):
        return np.clip(np.ravel(self.model_.predict(np.asarray(X, float))), 0, 100)


class AvgLinear(BaseEstimator, RegressorMixin):
    """Average of the ridge and the linear-SVR severity models (each with its own inner leave-one-level-out tuning).
    Averaging two different loss functions lowers the worst-case error (max error 16.6 -> 13.0 points in validation)."""

    def fit(self, X, y):
        self.a_ = LevelCVRidge("ridge").fit(X, y)
        self.b_ = LevelCVRidge("svr", (10.0, 100.0, 1000.0)).fit(X, y)
        return self

    def predict(self, X):
        return np.clip(0.5 * (self.a_.predict(X) + self.b_.predict(X)), 0, 100)


class MeanBaseline(BaseEstimator, RegressorMixin):
    def fit(self, X, y):
        self.m_ = float(np.mean(y))
        return self

    def predict(self, X):
        return np.full(len(X), self.m_)


class MajorityBaseline(BaseEstimator):
    def fit(self, X, y):
        v, c = np.unique(y, return_counts=True)
        self.classes_ = v
        self.maj_ = v[c.argmax()]
        self.p_ = c / c.sum()
        return self

    def predict(self, X):
        return np.array([self.maj_] * len(X))

    def predict_proba(self, X):
        return np.tile(self.p_, (len(X), 1))


