def p_de(model, X):
    """Score for class 'DE' from whatever the model offers (probability or decision function)."""
    cls = list(model.classes_) if hasattr(model, "classes_") else list(model[-1].classes_)
    j = cls.index("DE")
    if hasattr(model, "predict_proba"):
        return model.predict_proba(X)[:, j]
    d = np.ravel(model.decision_function(X))
    return 1 / (1 + np.exp(-(d if cls[1] == "DE" else -d)))


