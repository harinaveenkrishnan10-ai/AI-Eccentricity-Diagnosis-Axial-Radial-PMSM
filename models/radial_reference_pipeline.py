def clean_table(df):
    """Drop excluded levels, exact duplicates and conflicting duplicates.  Returns (clean_df, messages)."""
    msgs = []
    if df.empty:
        return df, msgs
    keep = ~df["level"].isin(EXCLUDE_LEVELS)
    for f in df.loc[~keep, "file"]:
        msgs.append(f"excluded by EXCLUDE_LEVELS: {f}")
    df = df[keep].copy()
    # conflicting labels with identical content
    bad = []
    for md5, g in df.groupby("md5"):
        if len(g) > 1 and g[["fault", "level"]].drop_duplicates().shape[0] > 1:
            bad += list(g["file"])
            msgs.append("IDENTICAL CONTENT BUT DIFFERENT LABELS (both removed): " + ", ".join(g["file"]))
    df = df[~df["file"].isin(bad)]
    dup = df.duplicated(subset=["md5", "fault", "level"], keep="first")
    for f in df.loc[dup, "file"]:
        msgs.append(f"identical copy skipped: {f}")
    df = df[~dup]
    # same file name seen twice in the store: keep the latest role/entry
    df = df.drop_duplicates(subset=["file"], keep="last")
    return df.reset_index(drop=True), msgs


def add_batch(df, centres=None):
    """Unsupervised run-batch indicator from the currents only (fundamental amplitude + 5th harmonic).
    The recordings fall into two clusters unrelated to eccentricity level (a simulation-setup offset).
    No labels are used.  Returns (df with 'Batch' column, centres)."""
    df = df.copy()
    X = df[["I1_A", "H5_pct"]].to_numpy(float)
    if centres is None:
        from sklearn.cluster import KMeans
        mu, sd = X.mean(0), X.std(0) + 1e-12
        km = KMeans(2, n_init=20, random_state=RANDOM_STATE).fit((X - mu) / sd)
        c = km.cluster_centers_
        if c[0, 0] > c[1, 0]:                       # label 0 = lower fundamental amplitude (like the Healthy file)
            c = c[::-1]
        centres = (mu, sd, c)
    mu, sd, c = centres
    Z = (X - mu) / sd
    df["Batch"] = np.argmin(((Z[:, None, :] - c[None]) ** 2).sum(-1), axis=1).astype(float)
    return df, centres


