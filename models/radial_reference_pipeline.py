def diagnose(bundle, row, verbose=True):
    xs = np.array([[row[c] for c in bundle["sev_features"]]], float)
    sev = float(bundle["sev_model"].predict(xs)[0])
    xc = np.array([[row[c] for c in bundle["clf_features"]]], float)
    pde = float(p_de(bundle["clf_model"], xc)[0])
    typ = "DE" if pde >= 0.5 else "SE"
    out_of_range = [c for c, v, lo, hi in zip(bundle["sev_features"], xs[0], bundle["feature_lo"], bundle["feature_hi"])
                    if v < lo or v > hi]
    v = bundle["val"]
    faulty = sev >= HEALTHY_THRESHOLD_PCT
    res = {"file": row["file"], "status": "FAULTY" if faulty else "HEALTHY", "severity": sev, "type": typ,
           "P_DE": pde, "type_reliable": v["clf_p"] <= 0.05 and v["clf_acc"] > v["clf_majority"],
           "out_of_range": out_of_range}
    if verbose:
        print("\n" + "=" * 70 + f"\nFILE: {row['file']}\n" + "=" * 70)
        print(f"STATUS        : {res['status']}"
              + ("" if faulty else f"   (estimate < {HEALTHY_THRESHOLD_PCT:g}%; Healthy rule rests on ONE healthy recording)"))
        q80_ = v.get("sev_q80", v["sev_mae"])
        lo_, hi_ = max(0.0, sev - q80_), min(100.0, sev + q80_)
        print(f"ECCENTRICITY  : approximately {sev:.1f} %   (80% interval {lo_:.0f}-{hi_:.0f} %; "
              f"validation MAE {v.get('sev_mae_interior', v['sev_mae']):.1f} points for interior levels, "
              f"{v['sev_mae']:.1f} incl. extremes; {v['n_train_files']} training files)")
        if faulty:
            tag = ("   (validation p = %.2f; classifier was selected on these same files, so treat as TENTATIVE)" % v["clf_p"]
                   if res["type_reliable"] else "   *** NOT RELIABLE: SE/DE not separable in validation (p = %.2f)" % v["clf_p"])
            print(f"FAULT TYPE    : {'Dynamic (DE)' if typ == 'DE' else 'Static (SE)'}  [tentative, P(DE) = {pde:.2f}]{tag}")
        if out_of_range:
            print("WARNING       : features outside the training range (extrapolation): " + ", ".join(out_of_range))
        try:
            tf, tl = parse_label(row["file"])
            print(f"(reference label from file name, never used for the diagnosis: {tf} {tl:g}%  ->  "
                  f"severity error {sev - tl:+.1f} points; type {'correct' if tf == typ else 'wrong'})")
        except Exception:
            pass
    return res


