def fit_bundle(train):
    """Fit the deployed models on ALL clean training files and attach the validation summary."""
    Xs, ys = train[SEV_FEATURES].to_numpy(float), train["level"].to_numpy(float)
    sev = AvgLinear().fit(Xs, ys)
    fa = train[train["fault"].isin(CLASSES)]
    clf = ExtraTreesClassifier(100, random_state=RANDOM_STATE, n_jobs=1).fit(fa[CLF_FEATURES].to_numpy(float), fa["fault"].to_numpy())
    # honest validation on the training files themselves
    prs = lolo_severity(train, SEV_FEATURES, {"base": lambda: MeanBaseline(), "m": lambda: AvgLinear()})
    f = train["level"].to_numpy() > 0
    y = train["level"].to_numpy(float)[f]
    mae, mae_base = np.abs(prs["m"][f] - y).mean(), np.abs(prs["base"][f] - y).mean()
    res = np.abs(prs["m"][f] - y)
    # interior levels = every faulty level except the lowest and the highest one (those two are extrapolations);
    # test levels normally lie inside the training range, so the interval is based on the interior errors.
    lv_f = train["level"].to_numpy(float)[f]
    inner = (lv_f > lv_f.min()) & (lv_f < lv_f.max())
    res_in = res[inner] if inner.sum() >= 3 else res
    mae_in = float(res_in.mean())
    q80 = float(np.quantile(res_in, 0.80, method="higher"))   # 80 % of interior-level errors were at most this large
    obs, pval, _ = perm_test_classifier(train, CLF_FEATURES, lambda: ExtraTreesClassifier(100, random_state=RANDOM_STATE, n_jobs=1), n_perm=100)
    lo = np.minimum(train[SEV_FEATURES].min().to_numpy(), train[SEV_FEATURES].max().to_numpy())
    hi = train[SEV_FEATURES].max().to_numpy()
    span = hi - lo
    return {"sev_model": sev, "clf_model": clf, "sev_features": SEV_FEATURES, "clf_features": CLF_FEATURES,
            "feature_lo": lo - 0.25 * span, "feature_hi": hi + 0.25 * span,
            "val": {"sev_q80": q80, "sev_mae_interior": mae_in, "sev_mae": float(mae), "sev_mae_baseline": float(mae_base), "clf_acc": obs, "clf_p": pval,
                    "clf_majority": float(fa["fault"].value_counts(normalize=True).max()), "n_train_files": int(len(train))},
            "settings": {"fs": FS_OUT, "exclude": sorted(EXCLUDE_LEVELS)}, "model_version": MODEL_VERSION}


