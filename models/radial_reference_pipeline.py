def parse_label(path):
    """healthy / static (SE) / dynamic (DE) + eccentricity % from the file name (used for labels only)."""
    name = Path(path).stem.lower().replace("-", "_")
    name = re.sub(r"\s+", "_", name)
    if "mixed" in name:
        raise ValueError(f"mixed eccentricity is not supported: {Path(path).name}")
    if "healthy" in name:
        return "Healthy", 0.0
    is_se = bool(re.search(r"stat|(?<=\d)st(?![a-z])|(?<![a-z])st(?![a-z])", name))
    is_de = bool(re.search(r"dyn|(?<=\d)dy(?![a-z])|(?<![a-z])dy(?![a-z])", name))
    if is_se == is_de:
        raise ValueError(f"name must contain healthy, static or dynamic: {Path(path).name}")
    pct = [float(x) for x in re.findall(r"(?<!\d)(\d+(?:\.\d+)?)\s*(?:%|pct)", name) if 0 <= float(x) <= 100]
    nums = pct or re.findall(r"(\d+(?:\.\d+)?)", name)
    if not nums:
        raise ValueError(f"no eccentricity level in file name: {Path(path).name}")
    return ("SE" if is_se else "DE"), float(nums[-1])


