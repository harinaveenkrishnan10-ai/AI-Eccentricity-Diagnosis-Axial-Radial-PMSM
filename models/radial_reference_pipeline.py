def load_currents(path):
    """Read an Ansys export.  Time may be on an irregular (adaptive-step) axis; returns t [s], x [3, n] [A]."""
    p = Path(path)
    df = pd.read_excel(p) if p.suffix.lower() in (".xls", ".xlsx") else pd.read_csv(p)

    def find(*keys):
        for c in df.columns:
            lc = str(c).lower().replace(" ", "").replace("-", "").replace("_", "")
            if all(k in lc for k in keys):
                return c
        return None

    tc = find("time")
    ph = [find("phasea") or find("ia"), find("phaseb") or find("ib"), find("phasec") or find("ic")]
    if tc is None or any(c is None for c in ph):
        raise ValueError(f"Time / Phase A,B,C columns not found in {p.name}. Columns: {list(df.columns)}")
    t = pd.to_numeric(df[tc], errors="coerce").to_numpy(float)
    x = np.vstack([pd.to_numeric(df[c], errors="coerce").to_numpy(float) for c in ph])
    ok = np.isfinite(t) & np.isfinite(x).all(axis=0)
    t, x = t[ok], x[:, ok]
    low = str(tc).lower()
    if "ms" in low:
        scale = 1e-3
    elif "us" in low or "µs" in low:
        scale = 1e-6
    elif "[s]" in low:
        scale = 1.0
    else:
        scale = 1e-3 if t.max() > 5 else 1.0               # guess: > 5 means milliseconds
    t, idx = np.unique(t * scale, return_index=True)        # sorted, no duplicate time stamps
    return t, x[:, idx]


def to_uniform(t, x, fs_out=FS_OUT, fs_mid=FS_MID):
    """Irregular samples -> fine uniform grid (linear) -> low-pass + decimate to fs_out (anti-aliased)."""
    tm = np.arange(t[0], t[-1], 1.0 / fs_mid)
    mid = np.vstack([np.interp(tm, t, xi) for xi in x])
    q = int(round(fs_mid / fs_out))
    return np.vstack([resample_poly(m, 1, q, window=("kaiser", 8.0), padtype="line") for m in mid])


def park(x):
    """Clarke / Park space vector  i_alpha + j*i_beta  of a [3, n] array."""
    return (2 * x[0] - x[1] - x[2]) / 3.0 + 1j * (x[1] - x[2]) / np.sqrt(3.0)


def lock_f0(z, fs):
    """Supply frequency (and rotation direction) from the Park vector: coarse FFT peak + fine local search."""
    n = len(z)
    w = np.hanning(n)
    nfft = 1 << 18
    Z = np.fft.fft(z * w, nfft)
    f = np.fft.fftfreq(nfft, 1 / fs)
    band = (np.abs(f) >= 20) & (np.abs(f) <= 1000)
    k = int(np.argmax(np.abs(Z) * band))
    sign = 1.0 if f[k] > 0 else -1.0
    zz = z if sign > 0 else np.conj(z)
    f0c, step, idx = abs(f[k]), fs / n, np.arange(n)
    res = minimize_scalar(lambda ff: -abs(np.sum(zz * w * np.exp(-2j * np.pi * ff * idx / fs))),
                          bounds=(f0c - step, f0c + step), method="bounded", options={"xatol": 1e-6})
    return float(res.x), sign


def harmonic_coeffs(xu, fs=FS_OUT):
    """Fourier coefficients c_k of the Park vector at k*f0 over a WHOLE number of cycles (zero leakage)."""
    i0 = int(round(TRANSIENT_S * fs))
    i1 = xu.shape[1] - int(round(END_TRIM_S * fs))
    z = park(xu[:, i0:i1])
    f0, sign = lock_f0(z, fs)
    if sign < 0:
        z = np.conj(z)
    per = fs / f0
    cycles = int(np.floor(len(z) / per))
    if cycles < 5:
        raise ValueError("record too short: need at least 5 steady-state cycles")
    L = int(round(cycles * per))
    n = np.arange(L)
    zc = z[:L]
    kmax = int(min(MAX_H, np.floor(0.4 * fs / f0)))
    C = {k: np.mean(zc * np.exp(-2j * np.pi * k * f0 * n / fs)) for k in range(-kmax, kmax + 1)}
    return C, f0, cycles, per, (i0, L), zc


def features_from_coeffs(C, f0, cycles, per, zc, xu, seg, fs=FS_OUT):
    """One feature dictionary per recording."""
    c1 = C[1]
    a1 = abs(c1)
    f = {"I1_A": a1}
    for k in (-5, 7, -11, 13):                                   # harmonics a symmetric inverter-fed machine HAS
        f[f"H{abs(k)}_pct"] = 100 * abs(C[k]) / a1
    # lines a symmetric 3-phase machine does NOT have (sequence rule: +1, -5, +7, -11, +13, ...): asymmetry
    allowed = {1} | {6 * m + 1 for m in range(1, 6)} | {-(6 * m + 5) for m in range(0, 6)}
    f["AsymM1_log"] = np.log10(100 * abs(C[-1]) / a1 + 1e-6)
    f["AsymP3_log"] = np.log10(100 * abs(C[3]) / a1 + 1e-6)
    f["AsymM3_log"] = np.log10(100 * abs(C[-3]) / a1 + 1e-6)
    f["AsymP5_log"] = np.log10(100 * abs(C[5]) / a1 + 1e-6)
    forbidden = [abs(C[k]) for k in C if k != 0 and k not in allowed]
    f["AsymIndex_pct"] = 100 * np.sqrt(np.sum(np.square(forbidden))) / a1
    for k in (-5, 7, -11, 13):                                   # harmonic phase relative to the fundamental (time-shift invariant)
        ph = np.angle(C[k]) - k * np.angle(c1)
        f[f"Ph{abs(k)}_cos"], f[f"Ph{abs(k)}_sin"] = float(np.cos(ph)), float(np.sin(ph))
    for k in LINE_ORDERS:                                        # amplitude of every analysed line (for plots)
        f[f"L{k:+d}"] = 100 * abs(C.get(k, 0.0)) / a1
    # quality checks
    i0, L = seg
    xs = xu[:, i0:i0 + L]
    f["RMS_A"] = float(np.sqrt((xs ** 2).mean(1)).mean())
    spc = int(round(per))
    if abs(per - spc) < 0.01:                                    # cycle-to-cycle repeatability
        cyc = xs[0, :cycles * spc].reshape(cycles, spc)
        f["cycle_dev_pct"] = float(100 * np.abs(cyc - cyc.mean(0)).max() / np.abs(xs[0]).max())
    else:
        f["cycle_dev_pct"] = np.nan
    spec = np.abs(np.fft.fft(zc)) / len(zc)                      # energy NOT on the harmonic grid (sidebands / noise)
    fr = np.fft.fftfreq(len(zc), 1 / fs)
    grid = np.arange(len(zc)) % cycles == 0
    off = (~grid) & (np.abs(fr) < 3000)
    f["offgrid_max_pct"] = float(100 * spec[off].max() / a1)
    f["f0_Hz"], f["cycles"] = float(f0), int(cycles)
    return f


def process_file(path, role):
    """CSV  ->  one row (labels + features + QC) for the feature store."""
    fault, level = parse_label(path)
    md5 = hashlib.md5(Path(path).read_bytes()).hexdigest()[:12]
    t, x = load_currents(path)
    xu = to_uniform(t, x)
    C, f0, cycles, per, seg, zc = harmonic_coeffs(xu)
    feats = features_from_coeffs(C, f0, cycles, per, zc, xu, seg)
    row = {"file": Path(path).name, "role": role, "fault": fault, "level": level, "md5": md5}
    row.update(feats)
    return row


def process_many(paths, default_role):
    rows = []
