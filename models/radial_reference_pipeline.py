def lolo_severity(df, feats, factories):
    """Hold out every faulty file of one level (SE_x and DE_x together); Healthy always stays in training."""
    X, y = df[feats].to_numpy(float), df["level"].to_numpy(float)
    out = {n: np.full(len(df), np.nan) for n in factories}
    for L in sorted(set(y[y > 0])):
        te = y == L
        for name, mk in factories.items():
            m = mk().fit(X[~te], y[~te])
            out[name][te] = np.clip(np.ravel(m.predict(X[te])), 0, 100)
    return out


def lolo_classify(df, feats, factories):
    d = df[df["fault"].isin(CLASSES)].reset_index(drop=True)
    X, y, lv = d[feats].to_numpy(float), d["fault"].to_numpy(), d["level"].to_numpy(float)
    pred = {n: np.empty(len(d), dtype=object) for n in factories}
    score = {n: np.full(len(d), np.nan) for n in factories}
    for L in sorted(set(lv)):
        te = lv == L
        for name, mk in factories.items():
            m = mk().fit(X[~te], y[~te])
            pred[name][te] = m.predict(X[te])
            try:
                score[name][te] = p_de(m, X[te])
            except Exception:
                pass
    return d, pred, score


def boot_ci(values, B=N_BOOT, seed=0, stat=np.mean):
    v = np.asarray(values, float)
    v = v[np.isfinite(v)]
    if len(v) < 2:
        return np.nan, np.nan
    rs = np.random.RandomState(seed)
    idx = rs.randint(0, len(v), size=(B, len(v)))
    return tuple(np.percentile([stat(v[i]) for i in idx], [2.5, 97.5]))


def severity_metrics(df, preds):
    f = df[df["level"] > 0]
    y = f["level"].to_numpy(float)
    base = np.abs(preds["Mean-predictor baseline"][f.index] - y).mean()
    rows = []
    for name, p in preds.items():
        p = p[f.index]
        e = np.abs(p - y)
        lo, hi = boot_ci(e)
        rows.append({"Model": name, "MAE (%)": e.mean(), "95% CI": f"[{lo:.1f}, {hi:.1f}]",
                     "RMSE (%)": float(np.sqrt(np.mean((p - y) ** 2))), "MedAE (%)": float(np.median(e)),
                     "MaxAE (%)": float(e.max()),
                     "R2": r2_score(y, p),
                     "Pearson r": float(np.corrcoef(y, p)[0, 1]) if np.std(p) > 1e-9 else np.nan,
                     "Skill vs baseline": 1 - e.mean() / base})
    return pd.DataFrame(rows)


def classification_metrics(d, pred, score):
    y = d["fault"].to_numpy()
    rows, extra = [], {}
    for name, p in pred.items():
        ok = (p == y).astype(float)
        lo, hi = boot_ci(ok)
        s = score[name]
        auc = roc_auc_score((y == "DE"), s) if np.isfinite(s).all() and len(set(y)) == 2 and np.std(s) > 0 else np.nan
        rows.append({"Model": name, "Accuracy": ok.mean(), "95% CI": f"[{lo:.2f}, {hi:.2f}]",
                     "Balanced acc.": balanced_accuracy_score(y, p), "Macro-F1": f1_score(y, p, average="macro"),
                     "MCC": matthews_corrcoef(y, p), "AUC (SE/DE)": auc})
    return pd.DataFrame(rows)


def perm_test_classifier(df, feats, make, n_perm=N_PERM_CLF, seed=1):
    d = df[df["fault"].isin(CLASSES)].reset_index(drop=True)
    obs = lolo_acc(d, feats, make)
    rs = np.random.RandomState(seed)
    null = []
    for _ in range(n_perm):
        dd = d.copy()
        dd["fault"] = rs.permutation(d["fault"].to_numpy())
        null.append(lolo_acc(dd, feats, make))
    null = np.array(null)
    return obs, float((np.sum(null >= obs) + 1) / (n_perm + 1)), null


def lolo_acc(d, feats, make):
    X, y, lv = d[feats].to_numpy(float), d["fault"].to_numpy(), d["level"].to_numpy(float)
    ok = []
    for L in sorted(set(lv)):
        te = lv == L
        if len(set(y[~te])) < 2:
            continue
        ok += list(make().fit(X[~te], y[~te]).predict(X[te]) == y[te])
    return float(np.mean(ok)) if ok else np.nan


def perm_test_severity(df, feats, n_perm=N_PERM_SEV, seed=2):
    """Shuffle the levels of the faulty files; compare MAE-improvement over the mean predictor."""
    mk = lambda: AvgLinear()
    base = lambda: MeanBaseline()

    def gain(d):
        pr = lolo_severity(d, feats, {"b": base, "m": mk})
        f = d["level"].to_numpy() > 0
        y = d["level"].to_numpy(float)[f]
        return np.abs(pr["b"][f] - y).mean() - np.abs(pr["m"][f] - y).mean()

    obs = gain(df)
    rs = np.random.RandomState(seed)
    idx = np.where(df["level"].to_numpy() > 0)[0]
    null = []
    for _ in range(n_perm):
        dd = df.copy()
        lv = dd["level"].to_numpy(float).copy()
        lv[idx] = rs.permutation(lv[idx])
        dd["level"] = lv
        null.append(gain(dd))
    return obs, float((np.sum(np.array(null) >= obs) + 1) / (n_perm + 1))


